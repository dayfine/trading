#!/bin/sh
# Generate the #3038 spec matrix: arm (overrides) x window (period + PIT schedule).
# Arms reuse the committed investor-preset overrides verbatim; the trader arms
# add ONE line each to the hybrid. Usage: sh gen-specs.sh  (writes ./specs/)
set -eu
HERE=$(cd "$(dirname "$0")" && pwd); OUT="$HERE/specs"; IP="$HERE/../investor-preset-2026-09-26/specs"
mkdir -p "$OUT"
# overrides block of a spec: from "(config_overrides" through the closing "  ))"
_ovr() { sed -n '/(config_overrides/,/^  ))/p' "$1"; }
# insert one line before the overrides block's closing "  ))" (POSIX awk, no GNU sed \n)
_add_before_close() { awk -v l="$1" '/^  \)\)$/ { print l } { print }'; }
_expected() { sed -n '/^ (expected/,$p' "$IP/inv5sc-hybrid.sexp"; }
# window header: name/description/period/universe_path/schedule/size
_header() { # $1 name $2 desc $3 start $4 end $5 first-vintage $6 last-vintage
  printf '((name "%s")\n (description "%s")\n (period ((start_date %s) (end_date %s)))\n' "$1" "$2" "$3" "$4"
  printf ' (universe_path "pit-v11/composition/top-3000-%s.sexp")\n (universe_schedule (\n' "$5"
  y=$5; while [ "$y" -le "$6" ]; do printf '  (%s-05-31 "pit-v11/composition/top-3000-%s.sexp")\n' "$y" "$y"; y=$((y+1)); done
  printf '  ))\n (universe_size 3000)\n'
}
_arm_ovr() { # $1 arm -> overrides block on stdout
  case $1 in
    I)  _ovr "$IP/inv5sc-investor.sexp" ;;
    H)  _ovr "$IP/inv5sc-hybrid.sexp" ;;
    T1) _ovr "$IP/inv5sc-hybrid.sexp" | _add_before_close "   ((enable_continuation_buys true))" ;;
    T0) _ovr "$IP/inv5sc-hybrid.sexp" | _add_before_close "   ((stage_config ((ma_period 10))))" ;;
  esac
}
_desc() { case $1 in
  I) echo "investor preset (inv5sc-investor overrides)";;
  H) echo "hybrid control (inv5sc-hybrid overrides)";;
  T1) echo "trader: hybrid + continuation buys (book's ideal trader entry)";;
  T0) echo "negative control: hybrid + 10-week STAGE MA (not book-supported)";; esac; }
for w in "5r 2021-06-01 2026-06-26 2020 2025" "5d 2007-06-01 2012-06-29 2006 2011" "26 2000-01-01 2026-06-26 1999 2025"; do
  set -- $w; win=$1; s=$2; e=$3; v0=$4; v1=$5
  for arm in I H T1 T0; do
    n=$(echo "tp-$arm-$win" | tr 'A-Z' 'a-z'); f="$OUT/$n.sexp"
    { printf ';; trader-presets-2026-09-29 (#3038): arm %s, window %s (%s -> %s). Generated by gen-specs.sh; do not hand-edit.\n' "$arm" "$win" "$s" "$e"
      printf ';; Staging scenario, NOT a golden. Both fill-model fixes on; max_one_share_class_per_issuer on (V6-comparable).\n'
      _header "$n" "$(_desc $arm), $win" "$s" "$e" "$v0" "$v1"; _arm_ovr $arm; _expected; } > "$f"
  done
done
ls "$OUT"
